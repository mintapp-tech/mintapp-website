-- Verified: gen_random_uuid() is used as the id default. Guarded here for
-- portability to Postgres versions where it isn't a core builtin yet.
create extension if not exists pgcrypto;

create table if not exists public.project_inquiries (
  id                     uuid primary key default gen_random_uuid(),
  created_at             timestamptz not null default now(),
  updated_at             timestamptz not null default now(),
  deleted_at             timestamptz,

  full_name              text not null,
  email                  text not null,
  phone                  text,
  company_name           text,
  company_url            text,
  country                text,

  preferred_language     text not null,
  project_type           text,
  project_description    text not null,
  budget_range           text,
  timeline               text,
  referral_source        text,

  consent_given          boolean not null default false,
  consent_at             timestamptz,

  lead_status            text not null default 'new',
  booking_status         text not null default 'not_booked',
  cal_booking_id         text,
  cal_booking_url        text,
  meeting_start_at       timestamptz,
  meeting_timezone       text,

  notification_status    text not null default 'pending',
  notification_sent_at   timestamptz,

  concept_pack_status    text not null default 'not_started',
  internal_notes         text,

  source_page            text,
  utm_source             text,
  utm_medium             text,
  utm_campaign           text,
  submission_error       text,

  -- Reconstructed: the live "consent_given" column comment explicitly
  -- references a "consent_required constraint" by name, which is strong
  -- evidence a check constraint like this exists. Named to match.
  constraint consent_required check (consent_given = true)
);

