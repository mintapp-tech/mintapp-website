create index if not exists project_inquiries_email_idx on public.project_inquiries (email);

-- Reconstructed: updated_at is default now() on insert only; without a
-- trigger it would never change on update. Standard idiomatic
-- implementation — the live trigger's exact function name could not be
-- confirmed through the Data API, but this produces equivalent behavior.
create or replace function public.set_project_inquiries_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists project_inquiries_set_updated_at on public.project_inquiries;
create trigger project_inquiries_set_updated_at
  before update on public.project_inquiries
  for each row
  execute function public.set_project_inquiries_updated_at();

